#!/usr/bin/env python3
"""Tests for prune-comments/scripts/list-changed-files.py.

Run with: python3 tests/test_list_changed_files.py
Stdlib-only. Each test runs in a throwaway repo with an isolated HOME.
"""
import importlib.util as _ilu
import os
import subprocess
import tempfile
import unittest
from unittest.mock import patch

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPT = os.path.join(os.path.dirname(HERE), "scripts", "list-changed-files.py")
_spec = _ilu.spec_from_file_location("list_changed_files", SCRIPT)
lcf = _ilu.module_from_spec(_spec)
_spec.loader.exec_module(lcf)

AUTHOR = ["-c", "user.name=t", "-c", "user.email=t@t"]


class RepoCase(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.repo = os.path.join(self._tmp.name, "repo")
        os.makedirs(self.repo)
        home = os.path.join(self._tmp.name, "home")
        os.makedirs(home)
        env = {"HOME": home, "GIT_CONFIG_NOSYSTEM": "1", "XDG_CONFIG_HOME": home}
        self._env = patch.dict(os.environ, env)
        self._env.start()
        self.git("init", "-q", "-b", "main")

    def tearDown(self):
        self._env.stop()
        self._tmp.cleanup()

    def git(self, *args):
        return subprocess.run(
            ["git", *args], cwd=self.repo, capture_output=True, text=True, check=True
        ).stdout

    def write(self, path, text):
        full = os.path.join(self.repo, path)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8") as fh:
            fh.write(text)

    def seed(self):
        self.write("a.py", "# Step 1: init\nx = 1\n")
        self.git("add", "-A")
        self.git(*AUTHOR, "commit", "-q", "-m", "init")

    def run_lcf(self, cwd=None):
        return lcf.run(cwd=cwd or self.repo)


class TestGuards(RepoCase):
    def test_not_a_repo(self):
        code, out = self.run_lcf(cwd=self._tmp.name)
        self.assertEqual((code, out["error"]), (1, "not-a-repo"))

    def test_clean_tree_stops(self):
        self.seed()
        code, out = self.run_lcf()
        self.assertEqual((code, out["error"]), (2, "no-changes"))

    def test_read_only(self):
        self.seed()
        self.write("a.py", "changed\n")
        self.git("add", "a.py")
        self.write("b.py", "new\n")
        before = (self.git("rev-parse", "HEAD"), self.git("write-tree"), self.git("status", "--porcelain"))
        self.run_lcf()
        after = (self.git("rev-parse", "HEAD"), self.git("write-tree"), self.git("status", "--porcelain"))
        self.assertEqual(before, after)


class TestScope(RepoCase):
    def test_staged_unstaged_untracked_and_skips_ignored(self):
        self.seed()
        self.write("a.py", "# changed\nx = 1\n")
        self.write("staged.py", "x = 2\n")
        self.git("add", "staged.py")
        self.write("new.ts", "// Step 1\nconst a = 1\n")
        self.write("dist/out.js", "// built\n")
        self.write("lib/app.min.js", "x\n")
        self.write("gen.go", "// Code generated by tool. DO NOT EDIT.\npackage x\n")
        self.write("package-lock.json", "{}\n")
        code, out = self.run_lcf()
        self.assertEqual(code, 0, out)
        self.assertEqual(out["scope"], ["a.py", "new.ts", "staged.py"])
        self.assertEqual(out["skipped"], 4)

    def test_gitignored_untracked_excluded(self):
        self.seed()
        self.write(".gitignore", "secret.py\n")
        self.write("secret.py", "x = 1\n")
        self.assertEqual(self.run_lcf()[1]["scope"], [".gitignore"])

    def test_deleted_files_not_in_scope(self):
        self.write("b.py", "z = 3\n")
        self.seed()
        os.remove(os.path.join(self.repo, "b.py"))
        self.write("a.py", "changed\n")
        self.assertEqual(self.run_lcf()[1]["scope"], ["a.py"])

    def test_repo_without_commits(self):
        self.write("a.py", "x = 1\n")
        self.git("add", "a.py")
        self.write("b.py", "y = 2\n")
        code, out = self.run_lcf()
        self.assertEqual((code, out["scope"]), (0, ["a.py", "b.py"]))

    def test_run_from_subdirectory(self):
        self.seed()
        self.write("pkg/mod.py", "x = 1\n")
        code, out = self.run_lcf(cwd=os.path.join(self.repo, "pkg"))
        self.assertEqual((code, out["scope"]), (0, ["pkg/mod.py"]))


if __name__ == "__main__":
    unittest.main()
